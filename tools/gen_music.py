#!/usr/bin/env python3
"""Original background music for SOUL ASCENSION, generated in code (no samples, recordings or external music): one quiet loop per episode theme.
Seamless loops (note tails wrap around the loop end). Output: assets/audio/music_<theme>.ogg (needs ffmpeg with libvorbis) plus a .wav next to a temp dir.
Run: python3 tools/gen_music.py [out_dir]        Themes: ep1 (Neon District, A minor), ep2 (Lantern Quarter, D dorian, bells), ep3 (Relay, E phrygian, drone + pings)
Licence: original work generated by this script for this project (the project owner's, no third-party material)."""
import math, os, subprocess, sys, wave
import numpy as np
SR = 32000
OUT = sys.argv[1] if len(sys.argv) > 1 else 'assets/audio'
def hz(m): return 440.0 * 2 ** ((m - 69) / 12.0)
def env_exp(n, decay): return np.exp(-np.arange(n) / SR * decay)
def add(buf, start, sig):
    n = len(buf); idx = (start + np.arange(len(sig))) % n      # wrap: tails ring over the loop seam
    np.add.at(buf, idx, sig)
def pad(buf, notes, length, vol, lfo_hz, phase=0.0):
    t = np.arange(length) / SR
    for m in notes:
        f = hz(m)
        sig = (np.sin(2*np.pi*f*t) + 0.5*np.sin(2*np.pi*f*1.003*t + 0.7) + 0.25*np.sin(2*np.pi*f*2*t)) / 1.75
        buf += sig * vol * (0.65 + 0.35*np.sin(2*np.pi*lfo_hz*t + phase + m))
def pluck(f, dur, bright=1.0):
    n = int(SR*dur); t = np.arange(n)/SR
    s = np.sin(2*np.pi*f*t) + 0.45*bright*np.sin(2*np.pi*2*f*t)*np.exp(-t*6) + 0.2*bright*np.sin(2*np.pi*3*f*t)*np.exp(-t*9)
    return s * np.exp(-t*3.2) * np.minimum(1, t*400)
def bell(f, dur):
    n = int(SR*dur); t = np.arange(n)/SR
    parts = [(1, 1.0, 1.6), (2.76, 0.5, 2.4), (5.4, 0.25, 3.5), (8.93, 0.12, 5.0)]
    s = sum(a*np.sin(2*np.pi*f*r*t)*np.exp(-t*d) for r, a, d in parts)
    return s * np.minimum(1, t*300)
def ping(f, dur):
    n = int(SR*dur); t = np.arange(n)/SR
    return np.sin(2*np.pi*f*t) * np.exp(-t*2.2) * np.minimum(1, t*200)
def echo(buf, delay_s, gain, taps=3):
    out = buf.copy()
    for k in range(1, taps+1): out += np.roll(buf, int(SR*delay_s*k)) * (gain**k)
    return out
def lowpass(x, a):
    y = np.empty_like(x); acc = 0.0
    for i in range(len(x)): acc += a*(x[i]-acc); y[i] = acc
    return y
def theme_ep1():
    bpm = 72; beat = 60/bpm; bars = 8; L = int(SR*beat*4*bars); buf = np.zeros(L)
    chords = [(45, 52, 57, 60), (41, 48, 53, 57), (43, 50, 55, 59), (40, 47, 52, 55)]   # Am F G Em (low voicing)
    for i in range(bars):
        part = np.zeros(int(SR*beat*4)); pad(part, chords[i % 4], len(part), 0.10, 0.12, i)
        part *= np.minimum(1, np.minimum(np.arange(len(part)), len(part)-np.arange(len(part)))/ (SR*0.8))
        add(buf, int(SR*beat*4*i), part)
    arp = [[69, 72, 76, 72], [65, 69, 72, 69], [67, 71, 74, 71], [64, 67, 71, 67]]
    for i in range(bars):
        for j in range(8):
            m = arp[i % 4][j % 4] + (12 if (i % 4 == 3 and j == 7) else 0)
            add(buf, int(SR*(beat*4*i + beat*0.5*j)), pluck(hz(m), 1.4)*0.05)
    return echo(lowpass(buf, 0.18), beat*0.75, 0.38)
def theme_ep2():
    bpm = 60; beat = 60/bpm; bars = 8; L = int(SR*beat*4*bars); buf = np.zeros(L)
    chords = [(50, 57, 62, 66), (55, 62, 66, 69), (47, 54, 59, 62), (52, 59, 64, 67)]    # D, G(add), Bm, Em: lantern-warm, dorian colour
    for i in range(bars):
        part = np.zeros(int(SR*beat*4)); pad(part, chords[i % 4], len(part), 0.085, 0.09, i*0.5)
        part *= np.minimum(1, np.minimum(np.arange(len(part)), len(part)-np.arange(len(part)))/ (SR*1.0))
        add(buf, int(SR*beat*4*i), part)
    scale = [74, 76, 78, 81, 83, 86, 81, 78]                                              # D major pentatonic-ish bells
    rot = [0, 3, 5, 2, 4, 1, 6, 3]
    for i in range(bars):
        for j, off in enumerate((0, 1.5, 2.5)):
            m = scale[rot[(i*3 + j) % 8]]
            add(buf, int(SR*(beat*4*i + beat*off)), bell(hz(m), 3.2)*0.045)
    return echo(lowpass(buf, 0.22), beat*1.5, 0.42)
def theme_ep3():
    bpm = 54; beat = 60/bpm; bars = 8; L = int(SR*beat*4*bars); buf = np.zeros(L)
    for i in range(bars):
        part = np.zeros(int(SR*beat*4)); pad(part, (40, 47, 52) if i % 4 < 2 else (41, 48, 53), len(part), 0.12, 0.07, i*0.3)
        part *= np.minimum(1, np.minimum(np.arange(len(part)), len(part)-np.arange(len(part)))/ (SR*1.2))
        add(buf, int(SR*beat*4*i), part)
    pings = [(0, 76), (3.5, 71), (8, 77), (12.5, 72), (16, 76), (19.5, 79), (24, 71), (28.5, 77)]  # sparse relay pings, E phrygian colour (F natural)
    for beat_at, m in pings:
        add(buf, int(SR*beat*beat_at), ping(hz(m), 4.0)*0.05)
    return echo(lowpass(buf, 0.14), beat*1.0, 0.5, 4)
def finish(x):
    x = x - x.mean(); x = x / (np.abs(x).max() + 1e-9) * 0.7
    return x
def write(name, x):
    pcm = (np.clip(x, -1, 1) * 32767).astype('<i2')
    wav = os.path.join('/tmp', name + '.wav')
    with wave.open(wav, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
    os.makedirs(OUT, exist_ok=True)
    ogg = os.path.join(OUT, name + '.ogg')
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-c:a', 'libvorbis', '-q:a', '3', ogg], check=True)
    seam = abs(float(x[0]) - float(x[-1]))
    rms = float(np.sqrt((x**2).mean()))
    print(f'{ogg}: {len(x)/SR:.1f} s, peak {np.abs(x).max():.2f}, rms {rms:.3f}, seam step {seam:.4f}, {os.path.getsize(ogg)//1024} KB')
if __name__ == '__main__':
    for n, f in (('music_ep1', theme_ep1), ('music_ep2', theme_ep2), ('music_ep3', theme_ep3)):
        write(n, finish(f()))
